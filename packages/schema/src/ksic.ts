/** 중분류 → 그 중분류를 품은 대분류. 사전에 없는 코드는 undefined. */
const SECTION_BY_DIVISION: Record<string, KsicSection> = Object.fromEntries(
  KSIC_SECTIONS.flatMap((s) => s.divisions.map((d) => [d, s] as const)),
);

/** 임의 깊이의 업종코드 → 중분류 2자리. 2자리 미만이면 null. */
export function ksicDivision(code: string | null | undefined): string | null {
  if (!code) return null;
  const d = code.trim().slice(0, 2);
  return d.length === 2 ? d : null;
}

/** 중분류 코드 → 항목명. 사전에 없으면 코드를 그대로 보여준다(정보 손실 없음). */
export function ksicDivisionName(division: string | null | undefined): string | null {
  if (!division) return null;
  return KSIC_DIVISIONS[division] ?? `중분류 ${division}`;
}

export function ksicSectionOf(division: string | null | undefined): KsicSection | null {
  if (!division) return null;
  return SECTION_BY_DIVISION[division] ?? null;
}
