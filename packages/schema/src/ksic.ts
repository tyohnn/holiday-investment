/**
 * KSIC(한국표준산업분류) 10차 — 대분류(section)·중분류(division) 사전.
 *
 * `companies.sector_code` 는 DART `induty_code` 이고 그 실체가 KSIC 인데, **깊이가
 * 제각각**이다(호스티드 상장사 2,648개 실측: 3자리 1,090 · 4자리 308 · 5자리 1,250).
 * 그래서 코드를 그대로 비교하면 같은 산업이 흩어진다 — 게임만 해도 5821·58211·58212·582
 * 네 갈래다. 앞 2자리(중분류)로 접으면 그 흔들림이 사라지므로, 산업 지도의 격자는
 * 중분류를 단위로 쓴다.
 *
 * 다만 중분류는 **행정 분류이지 밸류체인이 아니다.** 이차전지 28개사만 해도 19(석유정제)
 * ·20(화학)·24(1차금속)·26(전자부품)·28(전기장비)·29(기계)·64(금융-지주) 일곱 중분류로
 * 흩어진다. 그래서 이 사전은 "아직 안 본 땅"을 빠짐없이 깔아 주는 배경일 뿐이고, 산업의
 * 경계 자체는 손으로 큐레이션한 카탈로그가 정본이다(apps/web/lib/industry/catalog.ts).
 *
 * 이름은 창작이 아니라 통계청 KSIC 10차 중분류 항목명을 옮긴 것이다. labels.ts 의
 * `SECTOR_NAMES`(세세분류 표시용, 부분 수록)와 역할이 다르다 — 그쪽은 종목 한 개의
 * 업종을 정확히 보여 주고, 이쪽은 전 상장사를 빠짐없이 덮는다.
 */

